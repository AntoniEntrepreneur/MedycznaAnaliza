def get_tree_explainer(
    model: Any,
    background_data: Optional[np.ndarray] = None,
) -> shap.Explainer:
    """Instantiate appropriate SHAP explainer (TreeExplainer for tree models, Explainer as fallback)."""
    classifier = model
    if hasattr(model, "named_steps"):
        if "classifier" in model.named_steps:
            classifier = model.named_steps["classifier"]
        elif hasattr(model, "steps") and len(model.steps) > 0:
            classifier = model.steps[-1][1]

    # Handle tree-based classifiers
    try:
        return shap.TreeExplainer(classifier)
    except Exception:
        # Fallback to general Explainer or LinearExplainer
        if hasattr(classifier, "coef_"):
            if background_data is not None:
                return shap.LinearExplainer(classifier, background_data)
        if background_data is not None:
            return shap.Explainer(classifier.predict_proba if hasattr(classifier, "predict_proba") else classifier.predict, background_data)
        return shap.Explainer(classifier)


def compute_shap_values(
    explainer: Any,
    X: Union[pd.DataFrame, np.ndarray],
) -> shap.Explanation:
    """Compute local SHAP attribution values, handling multi-class outputs for binary stroke target."""
    explanation = explainer(X)

    # For binary classification multi-class output (e.g. RandomForest with shape [N, Features, 2])
    if len(explanation.shape) == 3 and explanation.shape[2] == 2:
        return explanation[:, :, 1]
    return explanation


def get_clinical_archetypes(
    test_df: Optional[pd.DataFrame] = None,
    pipeline_or_model: Any = None,
    threshold: float = 0.07,
    random_state: int = 42,
) -> Dict[str, Dict[str, Any]]:
    """Identify 3 clinical archetypes (True Positive, True Negative, Borderline) from test cohort."""
    if test_df is None or pipeline_or_model is None:
        cohorts = get_curated_cohorts()
        df = cohorts.adult.copy()
        if "gender" in df.columns:
            df = df[df["gender"] != "Other"].copy()
        if "age" in df.columns:
            df = df[df["age"] >= 18.0].copy()
        df = df.reset_index(drop=True)

        feature_cols = [c for c in DEFAULT_FEATURE_COLS if c in df.columns]
        X = df[feature_cols].copy()
        y = df[TARGET_COL].astype(int).values

        _, X_test, _, y_test = train_test_split(
            X, y, test_size=0.20, stratify=y, random_state=random_state
        )
        X_test = X_test.reset_index(drop=True)

        if pipeline_or_model is None:
            from src.ml import load_production_pipeline
            artifact = load_production_pipeline()
            model = artifact["pipeline"]
            cutoff = artifact.get("optimal_threshold", threshold)
        else:
            model = pipeline_or_model
            cutoff = threshold
    else:
        X_test = test_df.drop(columns=[TARGET_COL, "id"], errors="ignore").reset_index(drop=True)
        y_test = test_df[TARGET_COL].astype(int).values if TARGET_COL in test_df.columns else np.zeros(len(test_df))
        model = pipeline_or_model
        cutoff = threshold

    try:
        probs = model.predict_proba(X_test)[:, 1]
    except Exception:
        # Fallback 1: Try categorical dtypes for LightGBM/CatBoost
        X_test_cat = X_test.copy()
        for col in CATEGORICAL_COLS:
            if col in X_test_cat.columns:
                X_test_cat[col] = X_test_cat[col].astype("category")
        try:
            probs = model.predict_proba(X_test_cat)[:, 1]
            X_test = X_test_cat
        except Exception:
            # Fallback 2: Try preprocessor if model was fitted on transformed features
            from src.ml import build_preprocessor
            pre = build_preprocessor()
            X_test_trans = pre.fit_transform(X_test)
            probs = model.predict_proba(X_test_trans)[:, 1]

    # Archetype 1: True Positive (High predicted risk, actual stroke=1)
    tp_mask = (y_test == 1) & (probs >= 0.25)
    if not np.any(tp_mask):
        tp_mask = y_test == 1
    tp_indices = np.where(tp_mask)[0]
    best_tp_idx = tp_indices[np.argmax(probs[tp_indices])]

    # Archetype 2: True Negative (Low predicted risk, actual stroke=0)
    tn_mask = (y_test == 0) & (probs < 0.03)
    if not np.any(tn_mask):
        tn_mask = y_test == 0
    tn_indices = np.where(tn_mask)[0]
    best_tn_idx = tn_indices[np.argmin(probs[tn_indices])]

    # Archetype 3: Borderline case (Moderate predicted risk near cutoff e.g. 8-15%, actionable)
    border_mask = (probs >= max(0.06, cutoff * 0.9)) & (probs <= min(0.18, cutoff * 2.2))
    border_indices = np.where(border_mask)[0]
    if len(border_indices) > 0:
        # Prioritize patient with modifiable factors (e.g. smoking or elevated BMI)
        best_border_idx = border_indices[0]
        for b_idx in border_indices:
            row = X_test.iloc[b_idx]
            if row.get("hypertension", 0) == 1 or row.get("smoking_status", "") in ("smokes", "formerly smoked"):
                best_border_idx = b_idx
                break
    else:
        # Fallback to closest prob to cutoff
        best_border_idx = int(np.argmin(np.abs(probs - cutoff)))

    archetypes = {
        "True Positive": {
            "archetype": "True Positive",
            "title_pl": "Wysokie Ryzyko (Potwierdzony Udar Mózgu)",
            "index": int(best_tp_idx),
            "patient": X_test.iloc[best_tp_idx].to_dict(),
            "patient_row": X_test.iloc[[best_tp_idx]].copy(),
            "true_label": int(y_test[best_tp_idx]),
            "predicted_risk": float(probs[best_tp_idx]),
            "risk_percent": float(probs[best_tp_idx] * 100.0),
            "threshold": cutoff,
            "description_pl": (
                "Pacjent geriatryczny z wielochorobowością naczyniową (podeszły wiek, "
                "wysoka glikemia, nadciśnienie tętnicze, choroba serca). Model precyzyjnie "
                "zidentyfikował skrajnie wysokie ryzyko incydentu naczyniowo-mózgowego."
            ),
        },
        "True Negative": {
            "archetype": "True Negative",
            "title_pl": "Niskie Ryzyko (Prawidłowy Brak Incydentu)",
            "index": int(best_tn_idx),
            "patient": X_test.iloc[best_tn_idx].to_dict(),
            "patient_row": X_test.iloc[[best_tn_idx]].copy(),
            "true_label": int(y_test[best_tn_idx]),
            "predicted_risk": float(probs[best_tn_idx]),
            "risk_percent": float(probs[best_tn_idx] * 100.0),
            "threshold": cutoff,
            "description_pl": (
                "Młody dorosły bez obciążeń naczyniowo-sercowych z prawidłowym poziomem "
                "glukozy i brakiem wywiadu nikotynowego. Wskaźniki protekcyjne dominują, "
                "utrzymując ryzyko znacznie poniżej progu badań przesiewowych."
            ),
        },
        "Borderline": {
            "archetype": "Borderline",
            "title_pl": "Przypadek Graniczny (Ryzyko Umiarkowane / Przy Progu Odcięcia)",
            "index": int(best_border_idx),
            "patient": X_test.iloc[best_border_idx].to_dict(),
            "patient_row": X_test.iloc[[best_border_idx]].copy(),
            "true_label": int(y_test[best_border_idx]),
            "predicted_risk": float(probs[best_border_idx]),
            "risk_percent": float(probs[best_border_idx] * 100.0),
            "threshold": cutoff,
            "description_pl": (
                "Pacjent w wieku dojrzałym z wybranymi modyfikowalnymi czynnikami ryzyka "
                "znajdujący się tuż przy klinicznym progu decyzyjnym. Kluczowy przypadek "
                "dla celowanej profilaktyki i modyfikacji stylu życia."
            ),
        },
    }

    return archetypes


def _parse_explanation_data(
    explanation_or_shap_values: Any,
    patient_row: Optional[Union[pd.Series, pd.DataFrame, Dict[str, Any]]] = None,
) -> Tuple[np.ndarray, float, List[str], List[Any]]:
    """Normalize various SHAP explanation representations into arrays and labels."""
    if isinstance(explanation_or_shap_values, shap.Explanation):
        exp = explanation_or_shap_values
        if len(exp.shape) > 1 and exp.shape[0] == 1:
            exp = exp[0]

        values = np.array(exp.values, dtype=float)
        base_value = float(exp.base_values) if hasattr(exp, "base_values") else 0.05
        feature_names = (
            list(exp.feature_names)
            if hasattr(exp, "feature_names") and exp.feature_names is not None
            else [f"Cecha_{i+1}" for i in range(len(values))]
        )
        data = list(exp.data) if hasattr(exp, "data") and exp.data is not None else [None] * len(values)

    elif isinstance(explanation_or_shap_values, pd.DataFrame):
        df_exp = explanation_or_shap_values
        feature_col = "feature" if "feature" in df_exp.columns else df_exp.columns[0]
        val_col = "shap_value" if "shap_value" in df_exp.columns else df_exp.columns[1]

        values = df_exp[val_col].to_numpy(dtype=float)
        feature_names = df_exp[feature_col].tolist()
        base_value = float(df_exp.attrs.get("base_value", getattr(df_exp, "base_value", 0.05)))
        data = df_exp["value"].tolist() if "value" in df_exp.columns else [None] * len(values)

    elif isinstance(explanation_or_shap_values, dict):
        d = explanation_or_shap_values
        feature_names = list(d.get("features", []))
        values = np.array(d.get("shap_values", []), dtype=float)
        base_value = float(d.get("base_value", 0.05))
        data = list(d.get("data", [None] * len(values)))

    else:
        values = np.array(explanation_or_shap_values, dtype=float).ravel()
        base_value = 0.05
        feature_names = [f"Cecha_{i+1}" for i in range(len(values))]
        data = [None] * len(values)

    # Merge patient_row data if provided
    if patient_row is not None:
        p_dict = patient_row.iloc[0].to_dict() if isinstance(patient_row, pd.DataFrame) else (
            patient_row.to_dict() if isinstance(patient_row, pd.Series) else dict(patient_row)
        )
        for i, fname in enumerate(feature_names):
            clean_name = fname
            for prefix in ("num__", "cat__", "bin__"):
                if clean_name.startswith(prefix):
                    clean_name = clean_name[len(prefix) :]
                    break
            if clean_name in p_dict:
                data[i] = p_dict[clean_name]

    return values, base_value, feature_names, data


def plot_shap_waterfall(
    explanation_or_shap_values: Any,
    patient_row: Optional[Union[pd.Series, pd.DataFrame, Dict[str, Any]]] = None,
    archetype_name: Optional[str] = None,
    title: Optional[str] = None,
    max_display: int = 8,
    save_path: Optional[Union[str, Path]] = None,
    as_plotly: bool = False,
) -> Union[plt.Figure, go.Figure]:
    """Render publication-grade SHAP waterfall chart with Polish clinical labels and units."""
    if as_plotly:
        return plot_shap_waterfall_plotly(
            explanation_or_shap_values=explanation_or_shap_values,
            patient_row=patient_row,
            archetype_name=archetype_name,
            title=title,
            max_display=max_display,
        )

    values, base_value, feature_names, data = _parse_explanation_data(
        explanation_or_shap_values, patient_row
    )

    # Sort features by absolute SHAP impact
    abs_indices = np.argsort(np.abs(values))[::-1]
    top_indices = abs_indices[:max_display]
    other_indices = abs_indices[max_display:]

    display_vals = []
    display_labels = []

    for idx in top_indices:
        v = values[idx]
        fname = feature_names[idx]
        val_item = data[idx] if idx < len(data) else None
        display_vals.append(v)
        display_labels.append(format_feature_label_pl(fname, val_item))

    if len(other_indices) > 0:
        other_sum = float(np.sum(values[other_indices]))
        display_vals.append(other_sum)
        display_labels.append(f"Pozostałe {len(other_indices)} cech")

    # Invert so largest push is near top
    display_vals = display_vals[::-1]
    display_labels = display_labels[::-1]

    n = len(display_vals)
    y_pos = np.arange(n)

    fig, ax = plt.subplots(figsize=(10.5, max(4.8, n * 0.48 + 1.4)), dpi=150)
    fig.patch.set_facecolor("#FFFFFF")
    ax.set_facecolor("#FFFFFF")

    cum = base_value
    # Draw waterfall step bars
    for i, (val, label) in enumerate(zip(display_vals, display_labels)):
        y = y_pos[i]
        color = "#DC2626" if val >= 0 else "#2563EB"
        left = cum if val >= 0 else cum + val
        width = abs(val)

        ax.barh(y, width, left=left, color=color, height=0.58, edgecolor="none", zorder=3)

        # Connector dotted line
        ax.plot([cum, cum], [y - 0.45, y + 0.45], color="#94A3B8", linestyle=":", linewidth=1.2, zorder=2)

        # Value annotation
        text_sign = "+" if val >= 0 else ""
        text_x = left + width + 0.01 if val >= 0 else left - 0.01
        ha = "left" if val >= 0 else "right"
        ax.text(
            text_x,
            y,
            f"{text_sign}{val:.2f}",
            va="center",
            ha=ha,
            fontsize=9.5,
            fontweight="bold",
            color="#0F172A",
        )
        cum += val

    final_pred = cum

    # Base value and final prediction reference lines
    ax.axvline(base_value, color="#64748B", linestyle="--", linewidth=1.3, zorder=1, label=f"Wartość bazowa E[f(X)] = {base_value:.2f}")
    ax.axvline(final_pred, color="#0F172A", linestyle="-", linewidth=1.6, zorder=1, label=f"Predykcja f(x) = {final_pred:.2f}")

    ax.set_yticks(y_pos)
    ax.set_yticklabels(display_labels, fontsize=10, color="#0F172A")
    ax.set_xlabel("Wkład w predykcję ryzyka (wartość SHAP)", fontsize=10.5, color="#334155")

    chart_title = title or (
        f"Analiza Kaskadowa SHAP (Waterfall): {archetype_name}"
        if archetype_name
        else "Analiza Kaskadowa SHAP (Wpływ Biomarkerów)"
    )
    ax.set_title(chart_title, fontsize=12.5, fontweight="bold", color="#0F172A", pad=14)

    # Clinical color legend
    from matplotlib.patches import Patch
    legend_elements = [
        Patch(facecolor="#DC2626", label="Czynniki nasilające ryzyko (+)"),
        Patch(facecolor="#2563EB", label="Czynniki protekcyjne (-)"),
    ]
    ax.legend(handles=legend_elements, loc="lower right", frameon=True, fontsize=9.5)

    ax.spines["top"].set_visible(False)
    ax.spines["right"].set_visible(False)
    ax.spines["left"].set_color("#CBD5E1")
    ax.spines["bottom"].set_color("#CBD5E1")
    ax.grid(axis="x", linestyle="--", alpha=0.5, color="#E2E8F0", zorder=0)

    plt.tight_layout()

    if save_path is not None:
        p = Path(save_path)
        p.parent.mkdir(parents=True, exist_ok=True)
        fig.savefig(p, bbox_inches="tight", dpi=150)

    return fig


def plot_shap_waterfall_plotly(
    explanation_or_shap_values: Any,
    patient_row: Optional[Union[pd.Series, pd.DataFrame, Dict[str, Any]]] = None,
    archetype_name: Optional[str] = None,
    title: Optional[str] = None,
    max_display: int = 8,
) -> go.Figure:
    """Render interactive Plotly horizontal waterfall chart for Streamlit workstation."""
    values, base_value, feature_names, data = _parse_explanation_data(
        explanation_or_shap_values, patient_row
    )

    abs_indices = np.argsort(np.abs(values))[::-1]
    top_indices = abs_indices[:max_display]
    other_indices = abs_indices[max_display:]

    display_vals = []
    display_labels = []

    for idx in top_indices:
        v = values[idx]
        fname = feature_names[idx]
        val_item = data[idx] if idx < len(data) else None
        display_vals.append(v)
        display_labels.append(format_feature_label_pl(fname, val_item))

    if len(other_indices) > 0:
        other_sum = float(np.sum(values[other_indices]))
        display_vals.append(other_sum)
        display_labels.append(f"Pozostałe {len(other_indices)} cech")

    # Prepare data for Plotly Waterfall
    # Base entry -> features -> Total entry
    y_categories = ["Wartość bazowa E[f(X)]"] + display_labels + ["Predykcja końcowa f(x)"]
    x_measures = ["absolute"] + ["relative"] * len(display_vals) + ["total"]
    x_values = [base_value] + display_vals + [None]

    text_labels = [f"<b>{base_value:.2f}</b>"] + [
        f"<b>{'+' if v >= 0 else ''}{v:.2f}</b>" for v in display_vals
    ] + [""]

    fig = go.Figure(
        go.Waterfall(
            name="SHAP",
            orientation="h",
            measure=x_measures,
            y=y_categories,
            x=x_values,
            text=text_labels,
            textposition="outside",
            increasing=dict(
                marker=dict(color="#DC2626", line=dict(color="#991B1B", width=1))
            ),
            decreasing=dict(
                marker=dict(color="#2563EB", line=dict(color="#1E40AF", width=1))
            ),
            totals=dict(
                marker=dict(color="#0F172A", line=dict(color="#020617", width=1))
            ),
            connector=dict(line=dict(color="#94A3B8", width=1.2, dash="dot")),
            hovertemplate=(
                "<b>%{y}</b><br>"
                "Wpływ: %{x:+.3f}<br>"
                "<extra></extra>"
            ),
        )
    )

    chart_title = title or (
        f"<b>Wykres Kaskadowy SHAP (Waterfall): {archetype_name}</b>"
        if archetype_name
        else "<b>Wykres Kaskadowy SHAP (Wpływ Biomarkerów)</b>"
    )

    fig.update_layout(
        title=dict(text=chart_title, font=dict(size=14, color="#0F172A")),
        template="plotly_white",
        height=max(400, len(y_categories) * 35 + 120),
        margin=dict(l=20, r=40, t=60, b=40),
        xaxis=dict(
            title="Wkład w predykcję ryzyka (wartość SHAP)",
            gridcolor="#F1F5F9",
            zeroline=True,
            zerolinecolor="#CBD5E1",
        ),
        yaxis=dict(
            gridcolor="#F8FAFC",
            tickfont=dict(size=10.5, color="#0F172A"),
        ),
    )

    return fig
