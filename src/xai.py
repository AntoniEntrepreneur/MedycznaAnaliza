def format_feature_label_pl(feature: str, value: Any = None) -> str:
    """Format feature name and optional clinical value into human-readable Polish label."""
    clean_feature = feature
    for prefix in ("num__", "cat__", "bin__"):
        if clean_feature.startswith(prefix):
            clean_feature = clean_feature[len(prefix) :]
            break

    base_label = FEATURE_LABELS_PL.get(
        feature, FEATURE_LABELS_PL.get(clean_feature, clean_feature.replace("_", " ").title())
    )

    if value is None:
        return base_label

    if isinstance(value, (bool, np.bool_)) or (isinstance(value, (int, np.integer)) and value in (0, 1) and "age" not in feature.lower()):
        val_str = "Tak" if bool(value) else "Nie"
        return f"{base_label} = {val_str}"

    if isinstance(value, (float, np.floating)):
        if "age" in feature.lower():
            return f"Wiek = {value:.0f} lat"
        if "glucose" in feature.lower():
            return f"Glikemia = {value:.1f} mg/dl"
        if "bmi" in feature.lower():
            return f"BMI = {value:.1f} kg/m²"
        return f"{base_label} = {value:.2f}"

    val_str = VALUE_TRANSLATIONS_PL.get(str(value), str(value))
    return f"{base_label} = {val_str}"


def get_feature_importances(
    model: Any,
    feature_names: Optional[List[str]] = None,
) -> pd.DataFrame:
    """Extract global feature importance values from pipeline, tree model, or linear classifier."""
    classifier = model
    detected_features = feature_names

    # Extract classifier and feature names from Pipeline if applicable
    if hasattr(model, "named_steps"):
        if "classifier" in model.named_steps:
            classifier = model.named_steps["classifier"]
        elif hasattr(model, "steps") and len(model.steps) > 0:
            classifier = model.steps[-1][1]

        if detected_features is None and "preprocessor" in model.named_steps:
            preprocessor = model.named_steps["preprocessor"]
            if hasattr(preprocessor, "get_feature_names_out"):
                try:
                    detected_features = list(preprocessor.get_feature_names_out())
                except Exception:
                    pass

    # Extract importance array
    if hasattr(classifier, "feature_importances_"):
        raw_importances = np.array(classifier.feature_importances_, dtype=float)
    elif hasattr(classifier, "coef_"):
        raw_importances = np.abs(np.ravel(classifier.coef_)).astype(float)
    elif hasattr(classifier, "calibrated_classifiers_"):
        fold_importances = []
        for c in classifier.calibrated_classifiers_:
            sub_est = getattr(c, "estimator", getattr(c, "base_estimator", None))
            if sub_est is not None:
                if hasattr(sub_est, "feature_importances_"):
                    fold_importances.append(sub_est.feature_importances_)
                elif hasattr(sub_est, "coef_"):
                    fold_importances.append(np.abs(np.ravel(sub_est.coef_)))
        if fold_importances:
            raw_importances = np.mean(fold_importances, axis=0).astype(float)
        else:
            raise ValueError("Could not extract feature importances from calibrated classifier.")
    else:
        raise ValueError(
            f"Model {type(classifier)} does not provide feature_importances_ or coef_ attributes."
        )

    n_feats = len(raw_importances)
    if detected_features is None or len(detected_features) != n_feats:
        detected_features = [f"Cecha_{i+1}" for i in range(n_feats)]

    total_imp = np.sum(raw_importances)
    normalized = (
        (raw_importances / total_imp) if total_imp > 0 else np.full(n_feats, 1.0 / n_feats)
    )

    df = pd.DataFrame(
        {
            "feature": detected_features,
            "label_pl": [
                FEATURE_LABELS_PL.get(f, format_feature_label_pl(f)) for f in detected_features
            ],
            "importance": raw_importances,
            "normalized_importance": normalized,
        }
    )

    return df.sort_values(by="importance", ascending=False).reset_index(drop=True)


def plot_global_feature_importance(
    importance_df: pd.DataFrame,
    top_n: int = 10,
    title: str = "Globalna Ważność Cech Klinicznych",
    save_path: Optional[Union[str, Path]] = None,
    as_plotly: bool = False,
) -> Union[plt.Figure, go.Figure]:
    """Render horizontal bar plot of global feature importance sorted descending."""
    if as_plotly:
        return plot_global_feature_importance_plotly(importance_df, top_n=top_n, title=title)

    df_top = importance_df.head(top_n).sort_values(by="importance", ascending=True).reset_index(drop=True)
    n = len(df_top)
    y_pos = np.arange(n)

    fig, ax = plt.subplots(figsize=(10, max(4.5, n * 0.45 + 1.2)), dpi=150)
    fig.patch.set_facecolor("#FFFFFF")
    ax.set_facecolor("#FFFFFF")

    # Gradient clinical navy styling
    bars = ax.barh(
        y_pos,
        df_top["normalized_importance"] * 100,
        color="#1E3A8A",
        height=0.62,
        edgecolor="#1E3A8A",
        alpha=0.92,
        zorder=3,
    )

    max_val = (df_top["normalized_importance"] * 100).max()
    ax.set_xlim(0, max_val * 1.22 if max_val > 0 else 100)

    # Value labels beside bars
    for bar, pct in zip(bars, df_top["normalized_importance"] * 100):
        ax.text(
            bar.get_width() + max_val * 0.015,
            bar.get_y() + bar.get_height() / 2,
            f"{pct:.1f}%",
            va="center",
            ha="left",
            fontsize=9.5,
            fontweight="bold",
            color="#0F172A",
        )

    ax.set_yticks(y_pos)
    ax.set_yticklabels(df_top["label_pl"], fontsize=10.5, color="#0F172A")
    ax.set_xlabel("Względny wkład w predykcję ryzyka udaru (%)", fontsize=10.5, color="#334155")
    ax.set_title(f"{title} (Top {n})", fontsize=13, fontweight="bold", color="#0F172A", pad=14)

    ax.spines["top"].set_visible(False)
    ax.spines["right"].set_visible(False)
    ax.spines["left"].set_color("#CBD5E1")
    ax.spines["bottom"].set_color("#CBD5E1")
    ax.grid(axis="x", linestyle="--", alpha=0.5, color="#E2E8F0", zorder=0)

    plt.tight_layout()

    if save_path is not None:
        p = Path(save_path)
        p.parent.mkdir(parents=True, exist_ok=True)
        fig.savefig(p, bbox_inches="tight", dpi=150)

    return fig


